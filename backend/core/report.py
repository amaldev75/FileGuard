"""
Builds the downloadable PDF verification report (uses the 'reportlab' library).
"""
from io import BytesIO

from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

RESULT_TEXT = {
    'VERIFIED': ('VERIFIED', colors.HexColor('#2F8F5B'),
                 'The file is identical to the approved original and its digital signature is valid.'),
    'TAMPERED': ('TAMPERED', colors.HexColor('#B8433F'),
                 'The file does not match the approved original. It has been modified after approval.'),
    'EXPIRED': ('EXPIRED', colors.HexColor('#C2702C'),
                'The file is identical to the approved original, but the admin\'s approval has expired.'),
    'NOT_REGISTERED': ('NOT REGISTERED', colors.HexColor('#B8862B'),
                       'No approved original with this file name exists for this user, so nothing could be compared.'),
}


def build_report(log):
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                            topMargin=20 * mm, bottomMargin=18 * mm, title='FileGuard Verification Report')
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle('h1', parent=styles['Title'], fontSize=22, alignment=0, spaceAfter=2)
    sub = ParagraphStyle('sub', parent=styles['Normal'], fontSize=10, textColor=colors.grey)
    body = ParagraphStyle('body', parent=styles['Normal'], fontSize=10.5, leading=15)
    mono = ParagraphStyle('mono', parent=styles['Normal'], fontName='Courier', fontSize=8.5, leading=11)
    small = ParagraphStyle('small', parent=styles['Normal'], fontSize=9, textColor=colors.grey, leading=12)

    label, color, explanation = RESULT_TEXT.get(log.result, RESULT_TEXT['NOT_REGISTERED'])
    rec = log.file_record

    story = [
        Paragraph('FileGuard', h1),
        Paragraph('Verification Report', sub),
        Spacer(1, 8 * mm),
    ]

    result_style = ParagraphStyle('res', parent=styles['Heading1'], fontSize=20, textColor=color, spaceAfter=2)
    story += [Paragraph(label, result_style), Paragraph(explanation, body), Spacer(1, 6 * mm)]

    def yn(value):
        return 'Passed' if value else 'Failed'

    rows = [
        ['Report ID', f'FG-{log.id:05d}'],
        ['Generated on', timezone.localtime().strftime('%d %b %Y, %H:%M')],
        ['Checked by (user)', log.owner.username],
        ['File name', log.filename],
        ['Checked at', timezone.localtime(log.checked_at).strftime('%d %b %Y, %H:%M:%S')],
    ]
    if log.result != 'NOT_REGISTERED':
        rows += [
            ['Integrity (SHA-256 match)', yn(log.integrity_passed)],
            ['Authenticity (digital signature)', yn(log.authenticity_passed)],
        ]
        if rec is not None:
            approver = rec.approved_by.username if rec.approved_by else 'N/A'
            when = timezone.localtime(rec.reviewed_at).strftime('%d %b %Y, %H:%M') if rec.reviewed_at else 'N/A'
            rows += [['Approved by (admin)', approver], ['Approved on', when]]
            if rec.expires_at:
                rows.append(['Valid until', timezone.localtime(rec.expires_at).strftime('%d %b %Y')])
            else:
                rows.append(['Valid until', 'No expiry'])

    table = Table([[Paragraph(f'<b>{a}</b>', body), Paragraph(str(b), body)] for a, b in rows],
                  colWidths=[58 * mm, 112 * mm])
    table.setStyle(TableStyle([
        ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#D9DDE0')),
        ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#F5F6F7')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 5), ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]))
    story += [table, Spacer(1, 6 * mm)]

    if log.result != 'NOT_REGISTERED':
        story += [
            Paragraph('<b>Approved (stored) SHA-256 hash</b>', body), Paragraph(log.stored_hash or '-', mono),
            Spacer(1, 3 * mm),
            Paragraph('<b>SHA-256 hash of the file checked</b>', body), Paragraph(log.current_hash or '-', mono),
            Spacer(1, 6 * mm),
        ]

    story += [
        Paragraph('<b>How this was checked</b>', body),
        Paragraph('1. The SHA-256 hash of the uploaded file was computed. '
                  '2. It was compared with the hash stored when an admin approved the original. '
                  '3. If the hashes matched, the RSA digital signature on the stored hash was verified '
                  'with the public key. Both checks must pass for a file to be Verified.', body),
        Spacer(1, 10 * mm),
        Paragraph('Generated by FileGuard: a secure file integrity and authenticity verification system.', small),
    ]
    doc.build(story)
    return buf.getvalue()